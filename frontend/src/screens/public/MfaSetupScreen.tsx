import React, { useEffect, useState } from 'react';
import { Linking, StyleSheet, Text, View } from 'react-native';
import { useAuth } from '../../auth/AuthContext';
import { errorMessage } from '../../api/client';
import { Banner, Button, Card, Field, Loading, Screen, Title } from '../../components/ui';
import { colors, radius, spacing, typography } from '../../theme';

export default function MfaSetupScreen() {
  const { beginMfaSetup, enableMfaCode, cancelChallenge, busy, pending, lastError, clearError } = useAuth();
  const [setup, setSetup] = useState<{ secret: string; otpauthUri: string } | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [code, setCode] = useState('');

  useEffect(() => {
    clearError();
    let active = true;
    beginMfaSetup()
      .then((response) => {
        if (active) setSetup({ secret: response.secret, otpauthUri: response.otpauthUri });
      })
      .catch((cause) => {
        if (active) setError(errorMessage(cause));
      })
      .finally(() => {
        if (active) setLoading(false);
      });
    return () => {
      active = false;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const submit = async () => {
    setError(null);
    if (code.trim().length < 6) {
      setError('Enter the 6-digit code generated by your authenticator.');
      return;
    }
    try {
      await enableMfaCode(code);
    } catch {
      // Error is surfaced by the auth context.
    }
  };

  return (
    <Screen>
      <Title subtitle="Your role requires two-factor authentication. Enrol an authenticator app to continue.">
        Set up two-factor authentication
      </Title>

      {loading ? <Loading label="Preparing your enrolment…" /> : null}
      {error || lastError ? (
        <Banner message={error ?? lastError ?? ''} onDismiss={() => {
          setError(null);
          clearError();
        }} />
      ) : null}

      {setup ? (
        <>
          <Card>
            <Text style={typography.h3}>1. Add the account to your app</Text>
            <Text style={[typography.bodyMuted, { marginTop: spacing.xs }]}>
              Use Google Authenticator, Microsoft Authenticator, 1Password, or any TOTP app.
            </Text>
            <Text style={[typography.small, { marginTop: spacing.md }]}>Setup key</Text>
            <View style={styles.secretBox}>
              <Text selectable style={styles.secret}>{setup.secret}</Text>
            </View>
            <Text style={[typography.small, { marginTop: spacing.sm }]}>otpauth URI</Text>
            <Text selectable style={[typography.small, { color: colors.primary }]} numberOfLines={3}>
              {setup.otpauthUri}
            </Text>
            <Button
              title="Open in authenticator app"
              variant="secondary"
              small
              style={{ marginTop: spacing.md, alignSelf: 'flex-start' }}
              onPress={() => Linking.openURL(setup.otpauthUri).catch(() => undefined)}
            />
          </Card>

          <Card>
            <Text style={typography.h3}>2. Verify a code</Text>
            <View style={{ height: spacing.md }} />
            <Field
              label="6-digit code"
              value={code}
              onChangeText={(value) => setCode(value.replace(/[^0-9]/g, '').slice(0, 6))}
              keyboardType="numeric"
              maxLength={6}
              placeholder="000000"
              style={styles.codeInput}
              required
              onSubmitEditing={submit}
            />
            <Button title="Enable MFA and continue" onPress={submit} loading={busy} disabled={busy} />
          </Card>
        </>
      ) : null}

      <Button
        title="Use a different account"
        variant="ghost"
        onPress={cancelChallenge}
        style={{ marginTop: spacing.sm }}
      />
      {pending ? <Text style={[typography.small, { textAlign: 'center' }]}>{pending.email}</Text> : null}
    </Screen>
  );
}

const styles = StyleSheet.create({
  secretBox: {
    backgroundColor: colors.surfaceMuted,
    borderRadius: radius.md,
    padding: spacing.md,
    marginTop: spacing.xs,
  },
  secret: { fontFamily: 'monospace', fontSize: 15, letterSpacing: 1.5, color: colors.text },
  codeInput: { fontSize: 24, letterSpacing: 8, textAlign: 'center', fontWeight: '700' },
});
